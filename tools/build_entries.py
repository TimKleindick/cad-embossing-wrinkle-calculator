"""Generate/check the two self-contained CAD entry source files, never binaries."""
import argparse
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]


def embedded_vbs_string(function, template):
    lines = [f'Function {function}()', '    Dim html', '    html = ""']
    for line in template.splitlines():
        quoted = line.replace('"', '""')
        lines.append(f'    html = html & "{quoted}" & vbLf')
    lines.extend([f'    {function} = html', 'End Function', ''])
    return '\n'.join(lines)


def generated_sources(root):
    root=Path(root)
    core=(root/'wrinkle/core.py').read_text(encoding='utf-8')
    nx=(root/'cad/nx/win32_dialog.py').read_text(encoding='utf-8')
    vba=(root/'cad/catia/WrinkleCore.bas').read_text(encoding='utf-8')
    core_vbs='\n'.join(line for line in vba.splitlines()
                      if not line.startswith('Attribute ') and line!='Option Explicit')
    cat=(root/'cad/catia/entry.vbs').read_text(encoding='utf-8')
    template = (root / 'cad/result.html').read_text(encoding='ascii')
    result_template = embedded_vbs_string('WResultTemplate', template)
    input_form = (root / 'cad/catia/input_form.ps1').read_text(encoding='ascii')
    sketch = json.loads((root / 'cad/input_sketch.json').read_text(encoding='ascii'))
    input_form = input_form.replace('{{INPUT_SKETCH}}', json.dumps(sketch, separators=(',', ':')))
    input_template = embedded_vbs_string('WInputFormScript', input_form)
    nx_lines = '\n'.join(f'    {line!r}' for line in template.splitlines(keepends=True))
    nx_template = f'REPORT_TEMPLATE = (\n{nx_lines}\n)\n'
    nx_template += f'INPUT_SKETCH = {sketch!r}\n'
    banner='# GENERATED by tools/build_entries.py; edit the source adapters instead.\n'
    return {
        'ready-to-run/NX_WrinkleCalculator.py':(banner+core+'\n'+nx_template+'\n'+nx).encode('utf-8'),
        'ready-to-run/CATIA_WrinkleCalculator.CATScript':(
            # CAA V5 requires Option Explicit first and omits the recorder's Language assignment.
            'Option Explicit\n'+
            "' GENERATED by tools/build_entries.py; CAD RUNTIME UNTESTED.\n"+
            core_vbs+'\n'+cat+'\n'+result_template+'\n'+input_template).encode('ascii'),
    }


def check_generated(root,expected):
    for name,data in expected.items():
        path=Path(root)/name
        if not path.is_file() or path.read_bytes()!=data:
            raise ValueError('generated entry missing/stale: '+name)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    expected=generated_sources(ROOT)
    if args.check:
        check_generated(ROOT,expected)
        print('PASS: both ready-to-run CAD sources match unchanged kernels and adapters')
    else:
        for name,data in expected.items():
            path=ROOT/name;path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(data)
            print('Generated '+name)

if __name__=='__main__': main()
